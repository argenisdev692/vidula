#!/usr/bin/env node
/**
 * syn — AI config sync (.claude/ → .cursor/)
 * ------------------------------------------------------------------
 * Keeps Cursor AI configuration in sync with the canonical .claude/
 * source and validates docs against the actual Laravel + Vue codebase.
 *
 * Ground truth is derived from code — NOT from the docs:
 *   - composer.json           → PHP, Laravel, Inertia, PHPUnit
 *   - package.json            → Vue, PrimeVue, Tailwind, Zod
 *   - resources/js/app.ts     → PrimeVue unstyled mode
 *   - vite.config.ts          → Inertia SSR flag
 *   - compose.yaml            → Sail services
 *
 * Usage:
 *   npx syn                 # check drift + sync .cursor/ (exit 1 if drift)
 *   npx syn --check         # check only, never write (CI / pre-commit gate)
 *
 * No external dependencies — runs on plain Node.
 */

import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  existsSync,
  readdirSync,
  statSync,
} from 'node:fs';
import { join, resolve, dirname, relative, sep, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const CHECK_ONLY = process.argv.includes('--check');
const GENERATED_BANNER = '<!-- GENERATED by `npx syn` — edit `.claude/` and re-run. DO NOT EDIT. -->\n\n';

const c = {
  red: (s) => `\x1b[31m${s}\x1b[0m`,
  green: (s) => `\x1b[32m${s}\x1b[0m`,
  yellow: (s) => `\x1b[33m${s}\x1b[0m`,
  cyan: (s) => `\x1b[36m${s}\x1b[0m`,
  dim: (s) => `\x1b[2m${s}\x1b[0m`,
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
};

const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');
const exists = (rel) => existsSync(join(ROOT, rel));

// ------------------------------------------------------------------
// Helpers
// ------------------------------------------------------------------
function parseFrontmatter(content) {
  const match = content.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) {
    return { frontmatter: {}, body: content };
  }

  const frontmatter = {};
  for (const line of match[1].split('\n')) {
    const m = line.match(/^([\w-]+)\s*:\s*(.+)$/);
    if (m) {
      frontmatter[m[1]] = m[2].replace(/^['"]|['"]$/g, '').trim();
    }
  }

  return { frontmatter, body: match[2] };
}

function extractFirstHeading(body) {
  const m = body.match(/^#\s+(.+)$/m);
  return m ? m[1].trim() : null;
}

function ensureDir(absPath) {
  mkdirSync(absPath, { recursive: true });
}

function writeGenerated(absPath, content) {
  ensureDir(dirname(absPath));
  writeFileSync(absPath, content);
}

function relPath(abs) {
  return relative(ROOT, abs).split(sep).join('/');
}

// ------------------------------------------------------------------
// 1. Ground truth — derived from the real code
// ------------------------------------------------------------------
function detectFacts() {
  const pkg = JSON.parse(read('package.json'));
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const composer = JSON.parse(read('composer.json'));
  const req = { ...composer.require, ...composer['require-dev'] };
  const appTs = exists('resources/js/app.ts') ? read('resources/js/app.ts') : '';
  const viteConfig = exists('vite.config.ts') ? read('vite.config.ts') : '';
  const compose = exists('compose.yaml') ? read('compose.yaml') : '';

  const sailServices = [...compose.matchAll(/^\s{4}(\w[\w.-]*):/gm)].map((m) => m[1]);

  return {
    php: req.php ?? 'unknown',
    laravel: req['laravel/framework'] ?? 'unknown',
    inertiaLaravel: req['inertiajs/inertia-laravel'] ?? 'unknown',
    vue: deps.vue ?? 'unknown',
    primevue: deps.primevue ?? 'absent',
    inertiaVue: deps['@inertiajs/vue3'] ?? 'absent',
    tailwind: Boolean(deps.tailwindcss),
    testRunner: req['phpunit/phpunit'] ? 'phpunit' : req['pestphp/pest'] ? 'pest' : 'unknown',
    unstyled: /unstyled\s*:\s*true/.test(appTs),
    hasZod: Boolean(deps['zod']),
    hasPiniaColada: Boolean(deps['@pinia/colada']),
    inertiaSsr: /inertia\s*\(\s*\{\s*ssr\s*:\s*true/.test(viteConfig),
    sailServices,
  };
}

// ------------------------------------------------------------------
// 2. Collect AI doc files (the things that drift)
// ------------------------------------------------------------------
function collectDocs() {
  const docs = [];
  const SKIP = new Set(['node_modules', '.git', '.cursor', '.devin', 'dist', 'vendor']);

  function walk(absDir) {
    for (const entry of readdirSync(absDir)) {
      if (SKIP.has(entry)) continue;
      const abs = join(absDir, entry);
      const st = statSync(abs);
      if (st.isDirectory()) walk(abs);
      else if (entry.endsWith('.md')) docs.push(abs);
    }
  }

  if (exists('.claude')) walk(join(ROOT, '.claude'));
  for (const f of ['CLAUDE.md', 'AGENTS.md']) {
    if (exists(f)) docs.push(join(ROOT, f));
  }

  return docs;
}

// ------------------------------------------------------------------
// 3. Drift rules
// ------------------------------------------------------------------
const NEG = /not used|not installed|no longer|never\b|❌|✅|\bNOT\b|\bno\b|wrong path|wrong\b|isn'?t used|deprecated|legacy|docker compose/i;
const NEG_LINE = /not used|❌|NOT\b|wrong|never\b/i;

function buildRules(facts) {
  const rules = [];

  if (facts.testRunner === 'phpunit' || facts.testRunner === 'pest') {
    rules.push({
      id: 'test-runner',
      bad: /\b(vitest|playwright)\b/i,
      allow: NEG,
      msg: `Test runner is "${facts.testRunner}" but a doc still references Vitest/Playwright.`,
    });
  }

  if (facts.unstyled) {
    rules.push({
      id: 'primevue-mode',
      bad: /preset\s*:/,
      allow: NEG,
      msg: 'PrimeVue runs in unstyled mode but a doc still shows a theme preset.',
    });
    rules.push({
      id: 'primeng-styled',
      bad: /primeng.*styled mode|styled theming via @primeuix/i,
      allow: NEG,
      msg: 'Stack uses PrimeVue unstyled + Volt but a doc references PrimeNG styled mode.',
    });
  }

  rules.push({
    id: 'bare-php-artisan',
    bad: /(?<!\.\/vendor\/bin\/sail )(?<!docker compose exec \w+ )php artisan\b/,
    allow: /never|NOT|❌|bare `php`|bare php|sail artisan/i,
    msg: 'Use `./vendor/bin/sail artisan` — bare `php artisan` is forbidden.',
  });

  rules.push({
    id: 'data-theme',
    bad: /data-theme/,
    allow: /never|NOT|❌|no `data-theme`|absence of class/i,
    msg: 'Theme toggling uses only `.dark` on `<html>` — `data-theme` is forbidden.',
  });

  rules.push({
    id: 'angular-stack',
    bad: /\b(@angular\/|Angular v\d|standalone\s*:\s*true)/,
    allow: NEG,
    msg: 'Stack is Vue 3 + Inertia but a doc references Angular patterns.',
  });

  return rules;
}

function scanDrift(docs, facts) {
  const rules = buildRules(facts);
  const findings = [];

  for (const abs of docs) {
    const rel = relPath(abs);
    const lines = read(rel).split(/\r?\n/);

    lines.forEach((line, i) => {
      for (const rule of rules) {
        if (rule.bad.test(line) && !rule.allow.test(line)) {
          findings.push({ rule: rule.id, msg: rule.msg, file: rel, line: i + 1, text: line.trim() });
        }
      }
    });
  }

  return findings;
}

// ------------------------------------------------------------------
// 4. Sync .claude/ → .cursor/
// ------------------------------------------------------------------
function factsMarkdown(facts) {
  const yn = (b) => (b ? 'yes' : 'no');
  return [
    '## Project ground truth (auto-detected from code)',
    '',
    '> Generated by `npx syn` — do not edit by hand.',
    '',
    `- **PHP:** ${facts.php}`,
    `- **Laravel:** ${facts.laravel}`,
    `- **Inertia (Laravel):** ${facts.inertiaLaravel}`,
    `- **Vue:** ${facts.vue} | **Inertia (Vue):** ${facts.inertiaVue}`,
    `- **PrimeVue:** ${facts.primevue} — ${facts.unstyled ? 'unstyled + Volt' : 'check app.ts config'}`,
    `- **Tailwind v4:** ${yn(facts.tailwind)} | **Inertia SSR:** ${yn(facts.inertiaSsr)}`,
    `- **Test runner:** ${facts.testRunner}`,
    `- **Zod:** ${yn(facts.hasZod)} | **Pinia Colada:** ${yn(facts.hasPiniaColada)}`,
    `- **Sail services:** ${facts.sailServices.join(', ') || 'none detected'}`,
    '',
  ].join('\n');
}

function ruleToMdc(sourceRel, content) {
  const { frontmatter, body } = parseFrontmatter(content);
  const name = basename(sourceRel, '.md');
  const alwaysApply =
    frontmatter.trigger === 'always_on' ||
    frontmatter.alwaysApply === 'true' ||
    frontmatter.alwaysApply === true;
  const description =
    frontmatter.description ||
    extractFirstHeading(body) ||
    `Synced from ${sourceRel}`;

  const lines = ['---'];
  if (alwaysApply) {
    lines.push('alwaysApply: true');
  } else {
    lines.push('alwaysApply: false');
  }
  lines.push(`description: ${description}`);
  if (frontmatter.globs) {
    lines.push(`globs: ${frontmatter.globs}`);
  }
  lines.push('---', '', GENERATED_BANNER, body.trimEnd(), '');

  return lines.join('\n');
}

function withGeneratedBanner(content, sourceRel) {
  const { frontmatter, body } = parseFrontmatter(content);
  if (Object.keys(frontmatter).length === 0) {
    return GENERATED_BANNER + content.trimEnd() + '\n';
  }

  const fm = Object.entries(frontmatter)
    .map(([k, v]) => `${k}: ${v}`)
    .join('\n');

  return `---\n${fm}\n---\n\n${GENERATED_BANNER}${body.trimEnd()}\n`;
}

function syncMarkdownTree(sourceRel, destRel, { transform } = {}) {
  const written = [];
  const sourceAbs = join(ROOT, sourceRel);

  if (!existsSync(sourceAbs)) {
    return written;
  }

  const st = statSync(sourceAbs);
  if (st.isFile()) {
    const destAbs = join(ROOT, destRel);
    const content = read(sourceRel);
    const output = transform ? transform(sourceRel, content) : withGeneratedBanner(content, sourceRel);
    writeGenerated(destAbs, output);
    written.push(destRel);
    return written;
  }

  function walk(srcDir, dstDir) {
    for (const entry of readdirSync(srcDir)) {
      const srcPath = join(srcDir, entry);
      const dstPath = join(dstDir, entry);
      const entrySt = statSync(srcPath);

      if (entrySt.isDirectory()) {
        walk(srcPath, dstPath);
      } else if (entry.endsWith('.md')) {
        const relSrc = relPath(srcPath);
        const relDst = relPath(dstPath);
        const content = readFileSync(srcPath, 'utf8');
        const output = transform ? transform(relSrc, content) : withGeneratedBanner(content, relSrc);
        writeGenerated(dstPath, output);
        written.push(relDst);
      }
    }
  }

  walk(sourceAbs, join(ROOT, destRel));
  return written;
}

function syncCursor(facts) {
  const written = [];

  // Rules: .claude/rules/*.md → .cursor/rules/*.mdc
  const rulesDir = join(ROOT, '.claude', 'rules');
  if (existsSync(rulesDir)) {
    for (const entry of readdirSync(rulesDir)) {
      if (!entry.endsWith('.md')) continue;
      const sourceRel = `.claude/rules/${entry}`;
      const destRel = `.cursor/rules/${entry.replace(/\.md$/, '.mdc')}`;
      const mdc = ruleToMdc(sourceRel, read(sourceRel));
      writeGenerated(join(ROOT, destRel), mdc);
      written.push(destRel);
    }
  }

  // CLAUDE.md (Laravel Boost) → .cursor/rules/laravel-boost.mdc
  if (exists('CLAUDE.md')) {
    const body = read('CLAUDE.md').trimEnd();
    const mdc = [
      '---',
      'alwaysApply: true',
      'description: Laravel Boost guidelines — framework versions, Sail, Inertia, PHPUnit conventions',
      '---',
      '',
      GENERATED_BANNER,
      body,
      '',
    ].join('\n');
    const destRel = '.cursor/rules/laravel-boost.mdc';
    writeGenerated(join(ROOT, destRel), mdc);
    written.push(destRel);
  }

  // Skills: .claude/skills/** → .cursor/skills/**
  written.push(...syncMarkdownTree('.claude/skills', '.cursor/skills'));

  // Top-level skill dirs outside skills/
  for (const dir of ['BACKEND-PHP', 'FRONTEND', 'OWASP']) {
    const skillRel = `.claude/${dir}/SKILL.md`;
    if (exists(skillRel)) {
      const destRel = `.cursor/skills/${dir}/SKILL.md`;
      writeGenerated(join(ROOT, destRel), withGeneratedBanner(read(skillRel), skillRel));
      written.push(destRel);
    }
  }

  // Commands: .claude/commands/*.md → .cursor/commands/*.md
  written.push(...syncMarkdownTree('.claude/commands', '.cursor/commands'));

  // Machine-readable facts + README
  const factsRel = '.cursor/project-facts.json';
  writeGenerated(join(ROOT, factsRel), JSON.stringify(facts, null, 2) + '\n');
  written.push(factsRel);

  const readmeRel = '.cursor/README.md';
  const readme = [
    GENERATED_BANNER,
    '# .cursor — AI configuration (synced)',
    '',
    'Canonical source: `.claude/` + `CLAUDE.md`. Re-generate with:',
    '',
    '```bash',
    'npx syn',
    '```',
    '',
    '## Layout',
    '',
    '- `rules/*.mdc` — always-on and contextual rules (from `.claude/rules/` + `CLAUDE.md`)',
    '- `skills/**/SKILL.md` — domain skills (architecture, backend, frontend, OWASP)',
    '- `commands/*.md` — slash commands for Cursor',
    '- `project-facts.json` — auto-detected stack versions',
    '',
    factsMarkdown(facts),
    '**Do not edit these files directly** — edit `.claude/` and run `npx syn`.',
    '',
  ].join('\n');
  writeGenerated(join(ROOT, readmeRel), readme);
  written.push(readmeRel);

  return written;
}

// ------------------------------------------------------------------
// Main
// ------------------------------------------------------------------
function main() {
  console.log(c.bold('\nsyn') + c.dim(` — .claude/ → .cursor/ (${CHECK_ONLY ? 'check only' : 'check + sync'})\n`));

  const facts = detectFacts();
  console.log(c.cyan('Ground truth:'));
  console.log(factsMarkdown(facts).split('\n').filter((l) => l.startsWith('- ')).join('\n'));
  console.log('');

  const docs = collectDocs();
  const findings = scanDrift(docs, facts);

  if (findings.length === 0) {
    console.log(c.green(`✔ No drift across ${docs.length} AI doc file(s).`));
  } else {
    console.log(c.red(`✖ ${findings.length} drift issue(s) found:`));
    for (const f of findings) {
      console.log(`  ${c.red('•')} ${c.bold(f.file + ':' + f.line)} ${c.dim('[' + f.rule + ']')}`);
      console.log(`    ${f.msg}`);
      console.log(`    ${c.dim(f.text)}`);
    }
  }

  if (!CHECK_ONLY) {
    const written = syncCursor(facts);
    console.log('\n' + c.green(`✔ Synced ${written.length} file(s) to .cursor/:`));
    for (const w of written) console.log('  ' + c.dim('→ ') + w);
  } else {
    console.log(c.dim('\n(--check: skipped writing .cursor/)'));
  }

  console.log('');
  if (findings.length > 0) {
    console.log(c.red('Drift detected — update the docs in .claude/ (or the code) and re-run `npx syn`.'));
    process.exit(1);
  }
}

main();
